/**
 * Какую единицу взять для короткой записи числа: по значению ПОСЛЕ округления.
 * Иначе 999 960 при одном знаке после запятой стало бы «1 000 тыс.», а не «1 млн».
 * units — по возрастанию: [[1e3, 'тыс.', 1], [1e6, 'млн', 2], …] (делитель, подпись, знаков после запятой,
 * необязательно — с какого числа брать единицу, если не с делителя: [1e3, 'тыс.', 1, 1e4]).
 * Возвращает индекс в units или -1, если число меньше первого порога.
 */
export function unitIndex(n, units) {
  const a = Math.abs(Number(n) || 0);
  let i = -1;
  while (i < units.length - 1 && a >= (units[i + 1][3] ?? units[i + 1][0])) i++;
  const rounded = j => { const [v, , d] = units[j]; return Math.round((a / v) * 10 ** d) / 10 ** d; };
  while (i >= 0 && i < units.length - 1 && rounded(i) >= 1000) i++;
  return i;
}
